@bp.post("/api/inbox/transcribe")
def inbox_transcribe():
    """Stream plain-text transcript for an inbox video via faster-whisper.

    Request JSON: ``{ "filename": "...", "language": "zh"|null }``
    Response: ``text/plain`` stream of recognized text (segment by segment).

    Requires optional media extras + ffmpeg on PATH::

        uv pip install -e '.[media]'

    Env:
      * ``SAU_WHISPER_MODEL`` — model size (default ``base``; also tiny/small/medium…)
    """
    payload = request.get_json(silent=True) or {}
    filename = payload.get("filename") or ""
    language = (payload.get("language") or "").strip() or None

    safe = _safe_filename(str(filename))
    if not safe:
        return jsonify({"success": False, "message": "无效的文件名"}), 400

    path = INBOX_DIR / safe
    if not path.is_file():
        # fuzzy match (same as /file/)
        matches = list(INBOX_DIR.glob(f"*{Path(filename).name}"))
        if matches:
            path = matches[0]
        else:
            return jsonify({"success": False, "message": "文件不存在，请先完成下载"}), 404

    # Reuse subtitle stack (lazy import so inbox works without media extras).
    try:
        from web_runner.routes.subtitle import (
            _deps_ok,
            _extract_audio,
            _get_model,
            _has_audio_stream,
        )
    except Exception as exc:  # pragma: no cover — import-time failure
        return jsonify({
            "success": False,
            "message": f"转写模块不可用: {exc}",
        }), 501

    ok, msg = _deps_ok()
    if not ok:
        return jsonify({
            "success": False,
            "message": (
                "转写功能需要安装语音识别依赖。\n"
                "请在项目根目录执行：\n"
                "  uv pip install -e '.[media]'\n"
                "然后重启后端（python run.py）。\n"
                "另需本机已安装 ffmpeg（macOS: brew install ffmpeg）。"
            ),
        }), 501

    # Fail fast before opening a stream when the file has no audio track.
    if not _has_audio_stream(path):
        return jsonify({
            "success": False,
            "message": "视频没有音轨，无法转写文案。请换一个带人声/旁白的视频。",
        }), 400

    # Capture path/lang in closure for the generator.
    video_path = path
    lang_hint = language

    def generate():
        audio = None
        try:
            log(f"[inbox] transcribe start {video_path.name}")
            # Explicit WAV extract keeps STT input predictable (16 kHz mono).
            audio = _extract_audio(video_path)
            model = _get_model()
            kwargs: dict = {
                "beam_size": 5,
                "vad_filter": True,
            }
            if lang_hint:
                kwargs["language"] = lang_hint
            segments, info = model.transcribe(str(audio), **kwargs)
            detected = getattr(info, "language", None)
            log(
                f"[inbox] transcribe running lang={detected or lang_hint or 'auto'} "
                f"file={video_path.name}"
            )
            n = 0
            for seg in segments:
                text = (getattr(seg, "text", None) or "").strip()
                if not text:
                    continue
                n += 1
                # Stream segment text; newline between segments reads better in UI.
                yield text + "\n"
            if n == 0:
                yield "（未识别到有效语音内容，请确认视频含人声）\n"
            log(f"[inbox] transcribe done {video_path.name} segments={n}")
        except FileNotFoundError as exc:
            # ffmpeg / ffprobe missing
            log(f"[inbox] transcribe missing tool: {exc}")
            yield (
                "转写失败：未找到 ffmpeg。\n"
                "macOS 安装：brew install ffmpeg\n"
                "安装后重启后端再试。\n"
            )
        except Exception as exc:  # strict-exceptions: allow boundary
            log(f"[inbox] transcribe failed: {type(exc).__name__}: {exc}")
            yield f"转写失败：{exc}\n"
        finally:
            if audio is not None:
                try:
                    Path(audio).unlink(missing_ok=True)
                except OSError:
                    pass

    return Response(
        generate(),
        mimetype="text/plain; charset=utf-8",
        headers={
            # Long videos can take minutes; discourage intermediary buffering.
            "X-Accel-Buffering": "no",
            "Cache-Control": "no-cache",
        },
    )


def _resolve_inbox_video(filename: str) -> Path | None:
    safe = _safe_filename(str(filename))
    if not safe:
        return None
    path = INBOX_DIR / safe
    if path.is_file():
        return path
    matches = list(INBOX_DIR.glob(f"*{Path(filename).name}"))
    return matches[0] if matches else None


@bp.post("/api/inbox/subtitle")
def inbox_subtitle():
    """Generate (and optionally burn-in) subtitles with NDJSON progress stream.

    Request JSON::

        {
          "filename": "video.mp4",
          "mode": "bilingual" | "zh" | "en" | "source",
          "burn": true,
          "burn_style": "auto" | "hard" | "soft",
          "quality": "original" | "1080" | "720"
        }

    Response: ``application/x-ndjson`` lines::

        {"type":"progress","phase":"extract","pct":10,"label":"…"}
        {"type":"done","data":{…}}
        {"type":"error","message":"…"}
    """
    import json as _json

    payload = request.get_json(silent=True) or {}
    filename = payload.get("filename") or ""
    mode = (payload.get("mode") or payload.get("lang") or "bilingual").strip().lower()
    burn = payload.get("burn", True)
    if isinstance(burn, str):
        burn = burn.lower() in ("1", "true", "yes", "on")
    burn_style = (payload.get("burn_style") or payload.get("style") or "auto").strip().lower()
    if burn_style not in ("auto", "hard", "soft"):
        burn_style = "auto"
    quality = (payload.get("quality") or "1080").strip().lower()

    path = _resolve_inbox_video(filename)
    if path is None:
        return jsonify({"success": False, "message": "文件不存在，请先完成下载"}), 404

    try:
        from web_runner.routes.subtitle import (
            SUB_DIR,
            _deps_ok,
            _extract_audio,
            _has_audio_stream,
            build_subtitle_tracks,
            burn_srt_onto_video,
        )
    except Exception as exc:
        return jsonify({"success": False, "message": f"字幕模块不可用: {exc}"}), 501

    ok, msg = _deps_ok()
    if not ok:
        return jsonify({
            "success": False,
            "message": (
                "添加字幕需要语音识别依赖。\n"
                "请执行：uv pip install -e '.[media]'\n"
                "并确保本机已安装 ffmpeg。"
            ),
        }), 501

    if not _has_audio_stream(path):
        return jsonify({
            "success": False,
            "message": "视频没有音轨，无法添加字幕。",
        }), 400

    video_path = path

    def generate():
        audio = None
        try:
            def emit(obj: dict):
                return _json.dumps(obj, ensure_ascii=False) + "\n"

            yield emit({"type": "progress", "phase": "extract", "pct": 8, "label": "提取音频…"})
            log(f"[inbox] subtitle start {video_path.name} mode={mode} burn={burn} q={quality}")
            audio = _extract_audio(video_path)

            progress_buf: list[tuple[str, int, str]] = []

            def on_progress(phase: str, pct: int, label: str) -> None:
                progress_buf.append((phase, pct, label))

            # Run track build (progress collected then flushed — whisper is sync)
            srt_text, _segs, detected, meta = build_subtitle_tracks(
                audio, mode, on_progress=on_progress,
            )
            for phase, pct, label in progress_buf:
                yield emit({"type": "progress", "phase": phase, "pct": pct, "label": label})

            SUB_DIR.mkdir(parents=True, exist_ok=True)
            tag = re.sub(r"[^a-z0-9_-]+", "", mode) or "sub"
            srt_name = f"{video_path.stem}_{tag}_{uuid.uuid4().hex[:8]}.srt"
            srt_path = SUB_DIR / srt_name
            srt_path.write_text(srt_text, encoding="utf-8")
            yield emit({"type": "progress", "phase": "compose", "pct": 88, "label": "字幕文件已写入…"})

            burned_name = None
            burned_url = None
            burn_method = None
            if burn:
                yield emit({
                    "type": "progress",
                    "phase": "burn",
                    "pct": 92,
                    "label": "写入视频（硬烧录可能需数分钟）…",
                })
                burned_name = f"{video_path.stem}_sub_{tag}.mp4"
                burned_path = INBOX_DIR / burned_name
                if burned_path.exists():
                    burned_name = f"{video_path.stem}_sub_{tag}_{uuid.uuid4().hex[:6]}.mp4"
                    burned_path = INBOX_DIR / burned_name
                _, burn_method = burn_srt_onto_video(
                    video_path,
                    srt_path,
                    burned_path,
                    lang=mode,
                    style=burn_style,
                    quality=quality,
                )
                burned_url = f"/api/inbox/file/{burned_name}"
                log(f"[inbox] subtitle attached → {burned_name} method={burn_method}")

            yield emit({"type": "progress", "phase": "done", "pct": 100, "label": "完成"})
            log(f"[inbox] subtitle done {video_path.name} mode={mode} lang={detected}")
            yield emit({
                "type": "done",
                "data": {
                    "mode": mode,
                    "detected_language": detected,
                    "meta": meta,
                    "srt_filename": srt_name,
                    "srt_url": f"/api/subtitle/file/{srt_name}",
                    "srt_text": srt_text,
                    "burned_filename": burned_name,
                    "burned_url": burned_url,
                    "burn_method": burn_method,
                    "quality": quality,
                },
            })
        except Exception as exc:  # strict-exceptions: allow boundary
            log(f"[inbox] subtitle failed: {type(exc).__name__}: {exc}")
            yield _json.dumps({
                "type": "error",
                "message": f"添加字幕失败：{exc}",
            }, ensure_ascii=False) + "\n"
        finally:
            if audio is not None:
                try:
                    Path(audio).unlink(missing_ok=True)
                except OSError:
                    pass

    return Response(
        generate(),
        mimetype="application/x-ndjson; charset=utf-8",
        headers={
            "X-Accel-Buffering": "no",
            "Cache-Control": "no-cache",
        },
    )


@bp.get("/api/inbox/thumb/<path:filename>")
def inbox_thumb(filename: str):
    """JPEG cover frame for list thumbnails (cached under media/thumbs)."""
    path = _resolve_inbox_video(filename)
    if path is None:
        return jsonify({"success": False, "message": "file not found"}), 404

    thumbs = BASE_DIR / "media" / "thumbs"
    thumbs.mkdir(parents=True, exist_ok=True)
    # Cache key includes mtime so re-downloads refresh
    mtime = int(path.stat().st_mtime)
    out = thumbs / f"{path.stem}_{mtime}.jpg"
    if not out.is_file():
        # Sweep old thumbs for same stem
        for old in thumbs.glob(f"{path.stem}_*.jpg"):
            _unlink_quiet(old)
        try:
            from web_runner.routes.subtitle import _resolve_ffmpeg
            ff = _resolve_ffmpeg(prefer_libass=False)
        except Exception:
            ff = "ffmpeg"
        cmd = [
            ff, "-y",
            "-ss", "1",
            "-i", str(path),
            "-frames:v", "1",
            "-vf", "scale=480:-2",
            "-q:v", "4",
            str(out),
        ]
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=120)
        if proc.returncode != 0 or not out.is_file():
            # retry without seek
            cmd2 = [
                ff, "-y", "-i", str(path),
                "-frames:v", "1", "-vf", "scale=480:-2", "-q:v", "5",
                str(out),
            ]
            proc2 = subprocess.run(cmd2, capture_output=True, text=True, timeout=120)
            if proc2.returncode != 0 or not out.is_file():
                return jsonify({"success": False, "message": "无法生成封面"}), 500
    return send_from_directory(thumbs, out.name, mimetype="image/jpeg", max_age=86400)


@bp.get("/api/inbox/storage")
def inbox_storage():
    """Disk usage for inbox + subtitles + thumbs."""
    from web_runner.routes.subtitle import SUB_DIR

    def _dir_stats(d: Path) -> dict:
        total = 0
        count = 0
        oldest = None
        newest = None
        if d.is_dir():
            for p in d.iterdir():
                if not p.is_file() or p.name.startswith("."):
                    continue
                st = p.stat()
                total += st.st_size
                count += 1
                oldest = st.st_mtime if oldest is None else min(oldest, st.st_mtime)
                newest = st.st_mtime if newest is None else max(newest, st.st_mtime)
        return {
            "bytes": total,
            "count": count,
            "oldest": time.strftime("%Y-%m-%dT%H:%M:%S", time.localtime(oldest)) if oldest else None,
            "newest": time.strftime("%Y-%m-%dT%H:%M:%S", time.localtime(newest)) if newest else None,
        }

    thumbs = BASE_DIR / "media" / "thumbs"
    inbox = _dir_stats(INBOX_DIR)
    subs = _dir_stats(SUB_DIR)
    th = _dir_stats(thumbs)
    return jsonify({
        "success": True,
        "data": {
            "inbox": inbox,
            "subtitles": subs,
            "thumbs": th,
            "total_bytes": inbox["bytes"] + subs["bytes"] + th["bytes"],
        },
    })


@bp.post("/api/inbox/cleanup")
def inbox_cleanup():
    """Delete inbox files older than N days. Optionally keep subtitled outputs.

    JSON: ``{ "older_than_days": 7, "keep_subtitled": true }``
    """
    payload = request.get_json(silent=True) or {}
    days = int(payload.get("older_than_days") or 7)
    keep_sub = payload.get("keep_subtitled", True)
    if isinstance(keep_sub, str):
        keep_sub = keep_sub.lower() in ("1", "true", "yes", "on")
    days = max(0, min(days, 3650))
    cutoff = time.time() - days * 86400

    to_delete: list[str] = []
    INBOX_DIR.mkdir(parents=True, exist_ok=True)
    for p in INBOX_DIR.iterdir():
        if not p.is_file() or p.name.startswith("."):
            continue
        if p.stat().st_mtime >= cutoff:
            continue
        if keep_sub and ("_sub_" in p.stem or p.stem.endswith("_sub")):
            continue
        to_delete.append(p.name)

    result = _delete_inbox_artifacts(to_delete)
    # stale thumbs
    thumbs = BASE_DIR / "media" / "thumbs"
    thumb_deleted = 0
    if thumbs.is_dir():
        for t in list(thumbs.iterdir()):
            if t.is_file() and t.stat().st_mtime < cutoff:
                if _unlink_quiet(t):
                    thumb_deleted += 1
    result["thumbs_deleted"] = thumb_deleted
    return jsonify({
        "success": True,
        "message": f"已清理 {len(result['deleted'])} 个过期文件",
        "data": result,
    })


