"""Inbox — share-link download + file serve + reveal + STT + subtitles.

Front-end: ``sau_web/frontend/src/api/inbox.ts``

Transcribe / subtitles use the optional ``stable-ts`` + ``faster-whisper`` stack
(``web_runner.routes.subtitle``; install: ``uv pip install -e '.[media]'``).

Cookie handling for authenticated downloads:
  * **YouTube**: Playwright ``storage_state`` → Netscape conversion.
  * **Bilibili**: ``biliup``-format cookie array → Netscape conversion.
  * If no cookie file is found and yt-dlp returns a "sign in" error, the
    response includes ``auth_required: true`` + ``platform`` so the UI
    can show a friendly guide to configure authorization.
"""
from __future__ import annotations

import hashlib
import json as _json
import os
import re
import subprocess
import time
import uuid
from pathlib import Path
from urllib.parse import urlparse

from flask import Blueprint, Response, jsonify, request, send_from_directory

from web_runner.utils import BASE_DIR, COOKIES_DIR, INBOX_DIR, log

bp = Blueprint("inbox", __name__)

_SAFE_NAME = re.compile(r"^[\w.\- +\u4e00-\u9fff]+$")


def _safe_filename(name: str) -> str | None:
    name = (name or "").strip()
    if not name or ".." in name or "/" in name or "\\" in name:
        return None
    base = Path(name).name
    if not base or base in (".", ".."):
        return None
    # Allow slightly broader charset by sanitizing instead of rejecting.
    cleaned = re.sub(r"[^\w.\- +\u4e00-\u9fff]", "_", base)
    return cleaned or None


def _url_fingerprint(url: str) -> str:
    return hashlib.sha1(url.encode("utf-8")).hexdigest()[:10]


# ── Platform cookie helpers ───────────────────────────────────────────
# YouTube & Bilibili download sometimes requires authentication. The
# account management system stores cookies in platform-specific formats:
#
#   YouTube:     Playwright ``storage_state`` JSON (cookies/youtube_*.json)
#   Bilibili:    ``biliup``-format JSON array (cookies/bilibili_*.json)
#
# yt-dlp expects Netscape cookie format. The helpers below bridge each
# platform's format to Netscape on-the-fly.

_PLATFORM_DOMAINS: dict[str, set[str]] = {
    "youtube": {"youtube.com", "www.youtube.com", "m.youtube.com",
                 "youtu.be", "music.youtube.com"},
    "bilibili": {"bilibili.com", "www.bilibili.com",
                  "m.bilibili.com", "b23.tv"},
}


def _is_platform_url(url: str, platform: str) -> bool:
    """Check if a URL belongs to the given platform (hostname-based)."""
    domains = _PLATFORM_DOMAINS.get(platform)
    if not domains:
        return False
    try:
        host = urlparse(url).hostname or ""
        return any(d in host for d in domains)
    except Exception:
        return False


def _find_platform_cookie_file(glob_pattern: str) -> Path | None:
    """Find the most recent valid cookie file matching a glob pattern.

    Scans ``COOKIES_DIR`` for files matching ``glob_pattern``. Accepts
    both Playwright ``storage_state`` (dict with ``cookies`` key) and
    raw cookie array formats (e.g. biliup).
    Returns the most recently modified valid file, or ``None``.
    """
    if not COOKIES_DIR.is_dir():
        return None
    candidates: list[Path] = []
    for p in COOKIES_DIR.glob(glob_pattern):
        try:
            data = _json.loads(p.read_text(encoding="utf-8"))
            if isinstance(data, dict) and data.get("cookies"):
                candidates.append(p)
            elif isinstance(data, list) and len(data) > 0:
                candidates.append(p)
        except (OSError, _json.JSONDecodeError):
            continue
    if not candidates:
        return None
    candidates.sort(key=lambda p: p.stat().st_mtime, reverse=True)
    return candidates[0]


def _find_youtube_cookie_file() -> Path | None:
    return _find_platform_cookie_file("youtube_*.json")


def _find_bilibili_cookie_file() -> Path | None:
    return _find_platform_cookie_file("bilibili_*.json")


def _storage_state_to_netscape_cookies(storage_state: dict) -> str:
    """Convert Playwright ``storage_state`` JSON to Netscape cookie format.

    Netscape format (``cookies.txt``) is what yt-dlp's ``cookiefile``
    option expects::

        .youtube.com	TRUE	/	TRUE	1769999999	SSID	abc123
        domain	includeSubdomain	path	httponly	expires	name	value

    Playwright ``storage_state`` has::

        {"cookies": [{"name": "SSID", "value": "abc123",
                       "domain": ".youtube.com", "path": "/",
                       "expires": 1769999999, "httpOnly": true,
                       "secure": true, "sameSite": "Lax"}],
         "origins": [...]}
    """
    lines = ["# Netscape HTTP Cookie File", "# Generated by social-auto-upload inbox"]
    cookies = storage_state.get("cookies", [])
    for c in cookies:
        domain = str(c.get("domain", ""))
        include_sub = "TRUE" if domain.startswith(".") else "FALSE"
        path = str(c.get("path", "/"))
        secure = "TRUE" if c.get("secure", False) else "FALSE"
        expires = int(c.get("expires", 0) or 0)
        name = str(c.get("name", ""))
        value = str(c.get("value", ""))
        lines.append(f"{domain}\t{include_sub}\t{path}\t{secure}\t{expires}\t{name}\t{value}")
    return "\n".join(lines)




def _write_temp_cookiefile(netscape_text: str) -> Path | None:
    """Write Netscape cookie text to a temp file for yt-dlp.

    Returns the file path, or None on failure. The caller is responsible
    for cleanup (the temp file sits in COOKIES_DIR with a ``.txt`` suffix
    and is unlinked after the download completes or on error).
    """
    try:
        path = COOKIES_DIR / f"_ytdlp_temp_{uuid.uuid4().hex[:12]}.txt"
        path.write_text(netscape_text, encoding="utf-8")
        return path
    except OSError:
        return None


def _needs_auth_download(error_message: str) -> bool:
    """Check if a yt-dlp error is due to missing authentication.

    Returns True if the error mentions sign-in, login, bot detection,
    or cookie requirements.
    """
    if not error_message:
        return False
    lowered = error_message.lower()
    triggers = [
        "sign in to confirm",
        "sign in",
        "login required",
        "authentication required",
        "this video requires",
        "you need to sign in",
        "cookies",
        "bot",
        "private video",
        "age-gate",
        "age restricted",
    ]
    return any(t in lowered for t in triggers)


@bp.post("/api/inbox/download")
def inbox_download():
    payload = request.get_json(silent=True) or {}
    url = (payload.get("url") or "").strip()
    if not url:
        return jsonify({"success": False, "message": "url is required"}), 400
    parsed = urlparse(url)
    if parsed.scheme not in ("http", "https") or not parsed.netloc:
        return jsonify({"success": False, "message": "invalid url"}), 400

    INBOX_DIR.mkdir(parents=True, exist_ok=True)
    ts = time.strftime("%Y%m%d_%H%M%S")
    fp = _url_fingerprint(url)
    # Restrict filenames for shell safety; keep title readable.
    outtmpl = str(INBOX_DIR / f"%(title).60s_{ts}_{fp}.%(ext)s")

    try:
        import yt_dlp  # type: ignore
    except ImportError:
        return jsonify({
            "success": False,
            "message": "yt-dlp not installed; run: uv pip install yt-dlp",
        }), 503

    # ── Platform cookie auto-detection ──────────────────────────────
    # Detect the platform from the URL and look for existing account
    # cookies, converting to Netscape format for yt-dlp automatically.
    cookiefile_path: Path | None = None
    cookie_src: Path | None = None
    download_platform: str | None = None

    if _is_platform_url(url, "youtube"):
        download_platform = "youtube"
        cookie_src = _find_youtube_cookie_file()
        if cookie_src is not None:
            try:
                storage_state = _json.loads(cookie_src.read_text(encoding="utf-8"))
                netscape = _storage_state_to_netscape_cookies(storage_state)
                cookiefile_path = _write_temp_cookiefile(netscape)
                if cookiefile_path:
                    log(f"[inbox] using YouTube cookies from {cookie_src.name}")
            except (OSError, _json.JSONDecodeError) as exc:
                log(f"[inbox] failed to read YouTube cookies {cookie_src.name}: {exc}")

    if _is_platform_url(url, "bilibili"):
        download_platform = "bilibili"
        cookie_src = _find_bilibili_cookie_file()
        if cookie_src is not None:
            try:
                raw = _json.loads(cookie_src.read_text(encoding="utf-8"))
                # biliup format: JSON array → storage_state via upstream converter
                if isinstance(raw, list):
                    # Reuse the authoritative biliup→storage_state converter from
                    # uploader. It only uses json + pathlib; no patchright deps.
                    try:
                        from uploader.bilibili_uploader.note import \
                            _convert_biliup_cookies_to_storage_state as _biliup_to_ss
                        storage_state = _biliup_to_ss(str(cookie_src))
                    except ImportError:
                        # Fallback: inline conversion
                        storage_state = {
                            "cookies": raw,
                            "origins": [{
                                "origin": "https://member.bilibili.com",
                                "localStorage": [],
                            }],
                        }
                    netscape = _storage_state_to_netscape_cookies(storage_state)
                elif isinstance(raw, dict) and raw.get("cookies"):
                    netscape = _storage_state_to_netscape_cookies(raw)
                else:
                    netscape = None
                if netscape:
                    cookiefile_path = _write_temp_cookiefile(netscape)
                    if cookiefile_path:
                        log(f"[inbox] using Bilibili cookies from {cookie_src.name}")
            except (OSError, _json.JSONDecodeError) as exc:
                log(f"[inbox] failed to read Bilibili cookies {cookie_src.name}: {exc}")

    ydl_opts: dict = {
        "outtmpl": outtmpl,
        "quiet": True,
        "no_warnings": True,
        "noprogress": True,
        "restrictfilenames": True,
        "retries": 3,
        "fragment_retries": 3,
        "socket_timeout": 60,
        "ignoreerrors": False,
        # Prefer a single progressive file when possible.
        "format": "bv*+ba/b",
        "merge_output_format": "mp4",
    }
    if cookiefile_path is not None:
        ydl_opts["cookiefile"] = str(cookiefile_path)

    _temp_cookiefile = cookiefile_path

    try:
        with yt_dlp.YoutubeDL(ydl_opts) as ydl:
            info = ydl.extract_info(url, download=True)
            if info is None:
                return jsonify({"success": False, "message": "extractor returned empty info"}), 502
            # playlist → take first entry
            if info.get("_type") == "playlist" and info.get("entries"):
                entries = [e for e in info["entries"] if e]
                info = entries[0] if entries else info
            filename = ydl.prepare_filename(info)
            # after merge, ext may be mp4
            path = Path(filename)
            if not path.exists():
                alt = path.with_suffix(".mp4")
                if alt.exists():
                    path = alt
        if not path.exists():
            candidates = sorted(
                INBOX_DIR.glob(f"*_{ts}_{fp}.*"),
                key=lambda p: p.stat().st_mtime,
                reverse=True,
            )
            if not candidates:
                candidates = sorted(
                    INBOX_DIR.glob(f"*_{ts}_*"),
                    key=lambda p: p.stat().st_mtime,
                    reverse=True,
                )
            if not candidates:
                return jsonify({"success": False, "message": "download finished but file missing"}), 502
            path = candidates[0]

        # Normalize weird characters for subsequent /file/<name> fetches
        safe = _safe_filename(path.name) or path.name
        final = INBOX_DIR / safe
        if final != path:
            try:
                if final.exists():
                    final.unlink()
                path.rename(final)
                path = final
            except OSError:
                path = path  # keep original

        # Cleanup temp cookiefile on success
        if _temp_cookiefile is not None and _temp_cookiefile.is_file():
            try:
                _temp_cookiefile.unlink()
            except OSError:
                pass

        size = path.stat().st_size if path.exists() else 0
        log(f"[inbox] downloaded {path.name} ({size} bytes) from {url}")
        return jsonify({
            "success": True,
            "filename": path.name,
            "engine": "yt-dlp",
            "dir": str(INBOX_DIR),
            "size": size,
            "data": {
                "filename": path.name,
                "engine": "yt-dlp",
                "dir": str(INBOX_DIR),
                "size": size,
                "title": (info or {}).get("title") if isinstance(info, dict) else None,
            },
        })
    except Exception as exc:  # strict-exceptions: allow boundary
        exc_msg = f"{type(exc).__name__}: {exc}"
        log(f"[inbox] download failed: {exc_msg}")

        # Check if this is an auth-required error
        auth_required = download_platform is not None and _needs_auth_download(str(exc))

        if auth_required and cookie_src is not None:
            # Has cookie file but still auth failed → cookies may be expired
            user_msg = (
                f"{download_platform.title()} 需要登录验证。当前已配置的 Cookie 可能已过期，"
                f"请前往「账号管理」重新授权 {download_platform.title()} 账号后重试。"
            )
        elif auth_required:
            if download_platform == "youtube":
                user_msg = (
                    "YouTube 需要登录验证才能下载此视频。"
                    "请先前往「账号管理」配置 YouTube 账号授权（扫码/登录 YouTube Studio），"
                    "完成后即可自动使用 Cookie 下载。"
                )
            elif download_platform == "bilibili":
                user_msg = (
                    "Bilibili 需要登录验证才能下载此视频（大会员内容/区域限制）。"
                    "请先前往「账号管理」配置 Bilibili 账号授权（扫码登录），"
                    "完成后即可自动使用 Cookie 下载。"
                )
            else:
                user_msg = f"{download_platform.title()} 需要登录验证才能下载此视频。"
        else:
            user_msg = f"下载失败：{exc}"

        body: dict = {
            "success": False,
            "message": user_msg,
        }
        if auth_required:
            body["auth_required"] = True
            body["platform"] = download_platform

        return jsonify(body), 502
    finally:
        # Always clean up temp cookiefile if it exists
        if _temp_cookiefile is not None and _temp_cookiefile.is_file():
            try:
                _temp_cookiefile.unlink()
            except OSError:
                pass


@bp.post("/api/inbox/organize")
def inbox_organize():
    """Copy selected inbox files into a date-based subdirectory for batch
    organization. Replaces the old download-zip endpoint.

    Request JSON::

        { "filenames": ["video1.mp4", "video2.mp4"] }

    Response::

        {
          "success": true,
          "message": "已归档 3 个文件到 下载组_2026-07-28",
          "data": {
            "dirname": "下载组_2026-07-28",
            "count": 3,
            "path": "/path/to/inbox/下载组_2026-07-28"
          }
        }
    """
    import shutil

    payload = request.get_json(silent=True) or {}
    filenames: list[str] = []
    raw_list = payload.get("filenames") or payload.get("files") or []
    if isinstance(raw_list, list):
        filenames = [str(x) for x in raw_list if x]

    if not filenames:
        return jsonify({"success": False, "message": "filenames required"}), 400

    # Deduplicate while preserving order
    seen: set[str] = set()
    uniq: list[str] = []
    for n in filenames:
        if n not in seen:
            seen.add(n)
            uniq.append(n)

    if len(uniq) > 50:
        return jsonify({"success": False, "message": "最多同时归档 50 个文件"}), 400

    INBOX_DIR.mkdir(parents=True, exist_ok=True)
    resolved: list[tuple[str, Path]] = []
    missing: list[str] = []

    for raw in uniq:
        name = raw.strip()
        safe = _safe_filename(name)
        if not safe:
            missing.append(name)
            continue
        path = INBOX_DIR / safe
        if not path.is_file():
            matches = list(INBOX_DIR.glob(f"*{Path(name).name}"))
            if matches:
                path = matches[0]
            else:
                missing.append(name)
                continue
        resolved.append((path.name, path))

    if not resolved:
        return jsonify({"success": False, "message": "没有可归档的文件"}), 404

    # Create date-based group directory
    date_str = time.strftime("%Y-%m-%d")
    group_dir = INBOX_DIR / f"\u4e0b\u8f7d\u7ec4_{date_str}"
    group_dir.mkdir(parents=True, exist_ok=True)

    copied = 0
    errors: list[str] = []
    for arcname, src in resolved:
        dst = group_dir / arcname
        try:
            if dst.exists():
                stem = Path(arcname).stem
                ext = Path(arcname).suffix
                dst = group_dir / f"{stem}_{uuid.uuid4().hex[:4]}{ext}"
            shutil.copy2(str(src), str(dst))
            copied += 1
        except OSError as exc:
            errors.append(f"{arcname}: {exc}")

    log(f"[inbox] organize: {copied} files -> {group_dir.name}")
    if missing:
        log(f"[inbox] organize missing: {missing}")
    if errors:
        log(f"[inbox] organize errors: {errors}")

    msg = f"\u5df2\u5f52\u6863 {copied} \u4e2a\u6587\u4ef6\u5230 {group_dir.name}"
    if errors:
        msg += f"\uff0c{len(errors)} \u4e2a\u5931\u8d25"

    return jsonify({
        "success": True,
        "message": msg,
        "data": {
            "dirname": group_dir.name,
            "count": copied,
            "path": str(group_dir),
        },
    })


@bp.get("/api/inbox/file/<path:filename>")
def inbox_file(filename: str):
    """Serve an inbox media file (inline). Supports Range for video seek/preview."""
    safe = _safe_filename(filename)
    if not safe:
        return jsonify({"success": False, "message": "invalid filename"}), 400
    path = INBOX_DIR / safe
    # also try original if sanitization changed nothing but file uses other name
    if not path.is_file():
        # fuzzy: match suffix fingerprint / basename
        matches = list(INBOX_DIR.glob(f"*{Path(filename).name}"))
        if matches:
            path = matches[0]
            safe = path.name
        else:
            return jsonify({"success": False, "message": "file not found"}), 404
    # conditional=True enables Range / If-None-Match so the browser can seek
    # without downloading the entire file for cover + preview playback.
    resp = send_from_directory(
        INBOX_DIR,
        safe,
        as_attachment=False,
        conditional=True,
        max_age=0,
    )
    resp.headers["Accept-Ranges"] = "bytes"
    # Allow canvas frame capture when UI is served from a different origin
    # (e.g. Vite :5174 → API :6001 without proxy).
    resp.headers["Access-Control-Allow-Origin"] = request.headers.get("Origin") or "*"
    resp.headers["Access-Control-Allow-Credentials"] = "true"
    return resp


@bp.get("/api/inbox/list")
def inbox_list():
    """List downloaded files for the inbox UI."""
    INBOX_DIR.mkdir(parents=True, exist_ok=True)
    files = []
    for p in sorted(INBOX_DIR.iterdir(), key=lambda x: x.stat().st_mtime, reverse=True):
        if not p.is_file() or p.name.startswith("."):
            continue
        st = p.stat()
        files.append({
            "filename": p.name,
            "size": st.st_size,
            "mtime": time.strftime("%Y-%m-%dT%H:%M:%S", time.localtime(st.st_mtime)),
        })
    return jsonify({"success": True, "data": files})


def _unlink_quiet(path: Path) -> bool:
    try:
        if path.is_file():
            path.unlink()
            return True
    except OSError as exc:
        log(f"[inbox] unlink failed {path.name}: {exc}")
    return False


def _delete_inbox_artifacts(
    filenames: list[str],
    *,
    srt_filenames: list[str] | None = None,
) -> dict:
    """Delete inbox videos (+ optional burned outputs) and related SRT files.

    Returns ``{deleted: [...], missing: [...], srt_deleted: [...]}``.
    """
    from web_runner.routes.subtitle import SUB_DIR

    deleted: list[str] = []
    missing: list[str] = []
    srt_deleted: list[str] = []
    stems: set[str] = set()

    for raw in filenames:
        name = (raw or "").strip()
        if not name:
            continue
        safe = _safe_filename(name)
        if not safe:
            missing.append(name)
            continue
        path = INBOX_DIR / safe
        if not path.is_file():
            # fuzzy basename match
            matches = list(INBOX_DIR.glob(f"*{Path(name).name}"))
            if matches:
                path = matches[0]
                safe = path.name
            else:
                missing.append(name)
                continue
        if _unlink_quiet(path):
            deleted.append(safe)
            stems.add(Path(safe).stem)
            log(f"[inbox] deleted file {safe}")
        else:
            missing.append(name)

    # Explicit SRT names from the client (if known)
    for raw in srt_filenames or []:
        sname = Path((raw or "").strip()).name
        if not sname or ".." in sname:
            continue
        sp = SUB_DIR / sname
        if _unlink_quiet(sp):
            srt_deleted.append(sname)

    # Also sweep SRTs that share a stem with deleted videos
    # e.g. video.mp4 → video_zh_abc.srt / video_bilingual_xyz.srt
    if stems and SUB_DIR.is_dir():
        for srt in list(SUB_DIR.iterdir()):
            if not srt.is_file() or not srt.name.endswith(".srt"):
                continue
            for stem in stems:
                if srt.name.startswith(stem + "_") or srt.stem == stem:
                    if _unlink_quiet(srt) and srt.name not in srt_deleted:
                        srt_deleted.append(srt.name)
                    break

    return {
        "deleted": deleted,
        "missing": missing,
        "srt_deleted": srt_deleted,
    }


@bp.post("/api/inbox/delete")
def inbox_delete():
    """Permanently delete one or more inbox files from disk.

    Request JSON::

        { "filename": "a.mp4" }
        { "filenames": ["a.mp4", "b.mp4"], "srt_filenames": ["a_zh_xxx.srt"] }
    """
    payload = request.get_json(silent=True) or {}
    filenames: list[str] = []
    if payload.get("filename"):
        filenames.append(str(payload["filename"]))
    raw_list = payload.get("filenames") or []
    if isinstance(raw_list, list):
        filenames.extend(str(x) for x in raw_list if x)

    # Deduplicate while preserving order
    seen: set[str] = set()
    uniq: list[str] = []
    for n in filenames:
        if n not in seen:
            seen.add(n)
            uniq.append(n)

    if not uniq:
        return jsonify({"success": False, "message": "请指定要删除的文件"}), 400

    srt_raw = payload.get("srt_filenames") or []
    srt_list = [str(x) for x in srt_raw] if isinstance(srt_raw, list) else []

    result = _delete_inbox_artifacts(uniq, srt_filenames=srt_list)
    # Treat "already gone" as success so UI can clear the row cleanly.
    if not result["deleted"] and result["missing"] and not result["srt_deleted"]:
        return jsonify({
            "success": True,
            "message": "文件已不存在，已从列表移除",
            "data": result,
        })
    return jsonify({
        "success": True,
        "message": f"已删除 {len(result['deleted'])} 个文件",
        "data": result,
    })


@bp.post("/api/inbox/clear")
def inbox_clear():
    """Permanently delete all files in the inbox directory (+ related SRTs)."""
    INBOX_DIR.mkdir(parents=True, exist_ok=True)
    names = [
        p.name for p in INBOX_DIR.iterdir()
        if p.is_file() and not p.name.startswith(".")
    ]
    result = _delete_inbox_artifacts(names)
    # Also wipe leftover subtitle files that may not match remaining stems
    try:
        from web_runner.routes.subtitle import SUB_DIR
        if SUB_DIR.is_dir():
            for srt in list(SUB_DIR.iterdir()):
                if srt.is_file() and srt.suffix.lower() == ".srt":
                    if _unlink_quiet(srt) and srt.name not in result["srt_deleted"]:
                        result["srt_deleted"].append(srt.name)
    except Exception as exc:
        log(f"[inbox] clear srt sweep: {exc}")

    log(f"[inbox] clear all: deleted={len(result['deleted'])} srt={len(result['srt_deleted'])}")
    return jsonify({
        "success": True,
        "message": f"已清空下载目录（{len(result['deleted'])} 个文件）",
        "data": result,
    })


